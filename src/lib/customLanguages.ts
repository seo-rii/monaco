import * as M from 'monaco-editor';

type MonacoModule = typeof import('monaco-editor');

type LanguageDefinition = {
	id: string;
	aliases: string[];
	extensions: string[];
	keywords: string[];
	lineComment?: string;
	blockComment?: [string, string];
	brackets?: [string, string][];
	extraRules?: M.languages.IMonarchLanguageRule[];
};

const WORD = /[A-Za-z_][\w']*/;
const STRING_RULES: M.languages.IMonarchLanguageRule[] = [
	[/"""[\s\S]*?"""/, 'string'],
	[/'''[\s\S]*?'''/, 'string'],
	[/"([^"\\]|\\.)*$/, 'string.invalid'],
	[/"([^"\\]|\\.)*"/, 'string'],
	[/'([^'\\]|\\.)*'/, 'string']
];

const NUMBER_RULES: M.languages.IMonarchLanguageRule[] = [
	[/0[xX][0-9a-fA-F_]+/, 'number.hex'],
	[/\b\d+(\.\d+)?([eE][+-]?\d+)?\b/, 'number']
];

function wordList(words: string[]) {
	return new RegExp(
		`\\b(?:${words.map((word) => word.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')).join('|')})\\b`
	);
}

function createTokenizer({
	keywords,
	lineComment,
	blockComment,
	brackets = [
		['{', '}'],
		['[', ']'],
		['(', ')']
	],
	extraRules = []
}: LanguageDefinition): M.languages.IMonarchLanguage {
	const comments: M.languages.IMonarchLanguageRule[] = [];
	if (lineComment) {
		comments.push([
			new RegExp(`${lineComment.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}.*$`),
			'comment'
		]);
	}
	if (blockComment) {
		comments.push([
			new RegExp(`${blockComment[0].replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}`),
			'comment',
			'@comment'
		]);
	}

	return {
		defaultToken: '',
		tokenPostfix: '',
		brackets: brackets.map(([open, close]) => ({ open, close, token: 'delimiter.bracket' })),
		tokenizer: {
			root: [
				...comments,
				...extraRules,
				...STRING_RULES,
				...NUMBER_RULES,
				[/[{}()[\]]/, '@brackets'],
				[keywords.length ? wordList(keywords) : /$^/, 'keyword'],
				[/[A-Z][\w']*/, 'type.identifier'],
				[WORD, 'identifier'],
				[/[;,.]/, 'delimiter'],
				[/[-+*/%=<>!&|:]+/, 'operator']
			],
			comment: blockComment
				? [
						[new RegExp(`[^${blockComment[0][0]}${blockComment[1][0]}]+`), 'comment'],
						[
							new RegExp(`${blockComment[0].replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}`),
							'comment',
							'@push'
						],
						[
							new RegExp(`${blockComment[1].replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}`),
							'comment',
							'@pop'
						],
						[/./, 'comment']
					]
				: []
		}
	};
}

